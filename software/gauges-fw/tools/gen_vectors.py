#!/usr/bin/env python3
"""Generate inc/s32k144_irq.h and src/vectors.c for the S32K144.

Source of truth: NXP "S32K1xx DMA Interrupt Mapping" workbook, Rev. 10
(25-FEB-2020), sheet S32K14x_INT_MAP_ARM, rows marked 'x' in the S32K144
column. Download it from the S32K1xx Reference Manual attachments (see
../../PLAN.md); it lives in software/refs/ (git-ignored). Only the output is
committed, so a normal build does not need the workbook.

The vector number in the workbook is the Cortex-M exception number; the NVIC
IRQ number is the vector number minus 16.

Usage: python gen_vectors.py <path to S32K1xx_DMA_Interrupt_mapping.xlsx>
"""
import os
import re
import sys
import warnings

warnings.filterwarnings("ignore")
import openpyxl  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)

# Names for the IRQs this firmware plans to use (each line is checked against
# the workbook's "Interrupt Type" text when the generator runs). Everything
# else gets a generic IRQn name.
NAMED = {
    17: "MCM", 18: "FTFC_CMD_COMPLETE", 19: "FTFC_READ_COLLISION", 20: "PMC_LVD",
    21: "FTFC_DOUBLE_BIT", 22: "WDOG_EWM", 23: "RCM", 28: "LPSPI2",
    39: "ADC0", 40: "ADC1",
    48: "LPIT0_CH0", 49: "LPIT0_CH1", 50: "LPIT0_CH2", 51: "LPIT0_CH3",
    57: "SCG", 59: "PORTA", 60: "PORTB", 61: "PORTC", 62: "PORTD", 63: "PORTE",
    78: "CAN0_ORED", 79: "CAN0_ERROR", 80: "CAN0_WAKEUP",
    81: "CAN0_MB0_15", 82: "CAN0_MB16_31",
    85: "CAN1_ORED", 86: "CAN1_ERROR", 88: "CAN1_MB0_15",
    92: "CAN2_ORED", 93: "CAN2_ERROR", 95: "CAN2_MB0_15",
    105: "FTM1_CH0_1", 106: "FTM1_CH2_3", 107: "FTM1_CH4_5", 108: "FTM1_CH6_7",
    109: "FTM1_FAULT", 110: "FTM1_OVF_RELOAD",
}
# Expected workbook text per named IRQ (substring, lower-case), so a wrong
# number cannot slip through silently.
EXPECT = {
    28: "lpspi", 39: "adc", 48: "lpit", 51: "lpit", 57: "scg bus",
    59: "porta", 63: "porte",
    78: "or", 79: "errors were detected", 81: "message buffer (0-15)",
    82: "message buffer (16-31)", 88: "message buffer (0-15)",
    105: "channel 0", 107: "channel 4", 109: "fault", 110: "overflow",
}

CORE = [  # (exception number, handler name) - Cortex-M4 system handlers
    (2, "NMI"), (3, "HardFault"), (4, "MemManage"), (5, "BusFault"),
    (6, "UsageFault"), (11, "SVC"), (12, "DebugMon"), (14, "PendSV"),
    (15, "SysTick"),
]


def load(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb["S32K14x_INT_MAP_ARM"]
    irq = {}
    for r in list(ws.iter_rows(values_only=True))[2:]:
        if r[2] is None or str(r[14]).strip() != "x":
            continue
        if not isinstance(r[3], int):
            continue
        irq.setdefault(r[3], []).append(
            (str(r[8]).replace("\n", " "), str(r[9]).replace("\n", " ")))
    return irq


def ident(s):
    return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()


def main():
    irq = load(sys.argv[1])
    top = max(irq)
    names = {}
    for n in range(top + 1):
        if n in NAMED:
            names[n] = NAMED[n]
            if n in EXPECT:
                text = " ".join(t for _, t in irq.get(n, [])).lower() + " " + \
                    " ".join(i for i, _ in irq.get(n, [])).lower()
                if EXPECT[n] not in text:
                    sys.exit(f"IRQ {n} named {NAMED[n]} but workbook says {text!r}")
        else:
            names[n] = f"IRQ{n}"
    # DMA channels share their numbers 0..15 plus error 16 in the workbook.
    for n in range(0, 16):
        names[n] = f"DMA{n}"
    names[16] = "DMA_ERROR"

    with open(os.path.join(FW, "inc", "s32k144_irq.h"), "w", newline="\n") as f:
        f.write("/* GENERATED by tools/gen_vectors.py from NXP S32K1xx DMA Interrupt Mapping\n"
                " * Rev. 10, sheet S32K14x_INT_MAP_ARM (S32K144 column). Do not edit. */\n")
        f.write("#ifndef S32K144_IRQ_H\n#define S32K144_IRQ_H\n\n")
        f.write("/* NVIC IRQ number = Cortex-M exception number - 16 */\n")
        f.write("typedef enum {\n")
        for n in range(top + 1):
            f.write(f"    {names[n]}_IRQn = {n},\n")
        f.write(f"    S32K144_IRQ_COUNT = {top + 1}\n" + "} IRQn_t;\n\n#endif\n")

    with open(os.path.join(FW, "src", "vectors.c"), "w", newline="\n") as f:
        f.write("/* GENERATED by tools/gen_vectors.py from NXP S32K1xx DMA Interrupt Mapping\n"
                " * Rev. 10, sheet S32K14x_INT_MAP_ARM (S32K144 column). Do not edit.\n"
                " * Every handler is a weak alias of Default_Handler; a driver overrides one\n"
                " * by defining a function of the same name. */\n")
        f.write('#include <stdint.h>\n\ntypedef void (*isr_t)(void);\n')
        f.write("extern uint32_t _estack;\nvoid Reset_Handler(void);\n\n"
                "/* An alias must target a symbol defined in this translation unit. */\n"
                "void Default_Handler(void)\n{\n"
                "    for (;;) { }    /* spurious IRQ: stop here under a debugger */\n}\n\n")
        decl = [f"{n}_Handler" for _, n in CORE] + [f"{names[i]}_IRQHandler" for i in range(top + 1)]
        for d in decl:
            f.write(f"void {d}(void) __attribute__((weak, alias(\"Default_Handler\")));\n")
        f.write("\n__attribute__((section(\".isr_vector\"), used))\n")
        f.write(f"const isr_t g_vectors[{16 + top + 1}] = {{\n")
        f.write("    (isr_t)&_estack,           /* 0: initial stack pointer */\n")
        f.write("    Reset_Handler,             /* 1: initial program counter */\n")
        core = dict(CORE)
        for v in range(2, 16):
            if v in core:
                f.write(f"    {core[v]}_Handler,\n")
            else:
                f.write("    0,                         /* reserved */\n")
        for i in range(top + 1):
            f.write(f"    {names[i]}_IRQHandler,\n")
        f.write("};\n")
    print(f"wrote inc/s32k144_irq.h and src/vectors.c ({16 + top + 1} vectors)")


if __name__ == "__main__":
    main()
