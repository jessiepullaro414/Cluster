#!/usr/bin/env python3
"""
Generates software/gauges-fw/test/test_codec.c: a C test whose expected bytes
and decoded values come from an INDEPENDENT implementation (cantools reading
cluster_private.dbc / car_haltech_v2.dbc plus the generator's Python CRC-8), so
a mistake in the generated C codec (cluster_codec.h) cannot hide behind itself.

Run: python can_protocol.py && python gen_codec_test.py
"""
import os

import cantools

import can_protocol as p

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "software", "gauges-fw", "test", "test_codec.c")


def raw_limits(s):
    lo = round((s["min"] - s["offset"]) / s["factor"])
    hi = round((s["max"] - s["offset"]) / s["factor"])
    return lo, hi


def pick_phys(s, idx):
    """A deterministic in-range physical value that sits exactly on the raw grid."""
    if s["length"] == 1:
        return idx % 2
    lo, hi = raw_limits(s)
    frac = (0.5, 0.25, 0.75, 0.4)[idx % 4]
    raw = lo + int((hi - lo) * frac)
    if s["length"] < 32:
        raw = max(lo, min(hi, raw))
    return raw * s["factor"] + s["offset"]


def c_num(v, kind):
    if kind == "float":
        return f"{v!r}f"
    return str(int(round(v)))


def main():
    db = cantools.database.load_file(os.path.join(HERE, "cluster_private.dbc"))
    hdb = cantools.database.load_file(os.path.join(HERE, "car_haltech_v2.dbc"))
    o = ['/* test_codec.c - GENERATED by protocol/gen_codec_test.py. Do not edit. */',
         "#include <math.h>", "#include <stdio.h>", "#include <string.h>",
         '#include "cluster_codec.h"', "",
         "static int failures;",
         '#define CHECK(c) do { if (!(c)) { printf("FAIL line %d: %s\\n", __LINE__, #c); failures++; } } while (0)',
         "#define NEAR(a, b, tol) (fabsf((float)(a) - (float)(b)) <= (tol))",
         "static int same(const uint8_t *a, const uint8_t *b) { return memcmp(a, b, 8) == 0; }", "",
         "int main(void)", "{"]
    for mi, m in enumerate(p.PRIVATE):
        msg = db.get_message_by_name(m["name"])
        sn = p.snake(m["name"])
        e2e = any(s["name"] == "Counter" for s in m["signals"])
        sigs = [s for s in m["signals"] if s["name"] not in ("Counter", "Crc8")]
        vals = {s["name"]: pick_phys(s, i + mi) for i, s in enumerate(sigs)}
        enc = dict(vals)
        counter = 9
        if e2e:
            enc["Counter"] = counter
            enc["Crc8"] = 0
        raw = bytearray(msg.encode(enc))
        if e2e:
            raw[7] = p.crc8(raw[:7])
        vec = ", ".join(f"0x{b:02X}" for b in raw)
        o.append(f"    {{ /* 0x{m['id']:03X} {m['name']} */")
        o.append(f"        const uint8_t vec[8] = {{ {vec} }};")
        o.append(f"        cluster_{sn}_t m; memset(&m, 0, sizeof m);")
        for s in sigs:
            k = p.field_kind(s)
            o.append(f"        m.{p.snake(s['name'])} = {c_num(vals[s['name']], k)};")
        o.append("        uint8_t out[8];")
        if e2e:
            o.append(f"        cluster_{sn}_pack(&m, {counter}, out);")
        else:
            o.append(f"        cluster_{sn}_pack(&m, out);")
        o.append(f'        CHECK(same(out, vec));')
        o.append(f"        cluster_{sn}_t u; memset(&u, 0, sizeof u);")
        o.append(f"        CHECK(cluster_{sn}_unpack(vec, &u) == 0);")
        for s in sigs:
            k = p.field_kind(s)
            f = p.snake(s["name"])
            if k == "float":
                tol = max(abs(s["factor"]) * 0.51, 1e-4)
                o.append(f"        CHECK(NEAR(u.{f}, {c_num(vals[s['name']], k)}, {tol!r}f));")
            else:
                o.append(f"        CHECK(u.{f} == {c_num(vals[s['name']], k)});")
        if e2e:
            o.append(f"        CHECK(u.counter == {counter});")
            o.append("        uint8_t bad[8]; memcpy(bad, vec, 8); bad[2] ^= 0x10;")
            o.append(f"        CHECK(cluster_{sn}_unpack(bad, &u) == -1);")
        o.append("    }")
    # Haltech: every signal, from raw bytes decoded by cantools
    for m in p.HALTECH:
        msg = hdb.get_message_by_name(m["name"])
        raw = bytearray(8)
        # put a different non-trivial 16-bit raw value into each field
        for i, s in enumerate(m["signals"]):
            byte = s["start"] // 8
            v = (0x0123 * (i + 2)) & 0x7FFF
            raw[byte] = v >> 8
            raw[byte + 1] = v & 0xFF
        dec = msg.decode(bytes(raw))
        vec = ", ".join(f"0x{b:02X}" for b in raw)
        o.append(f"    {{ /* 0x{m['id']:03X} {m['name']} */")
        o.append(f"        const uint8_t vec[8] = {{ {vec} }};")
        for s in m["signals"]:
            exp = float(dec[s["name"]])
            o.append(f"        CHECK(NEAR(cluster_{p.snake(m['name'])}_{p.snake(s['name'])}(vec), {exp!r}f, 0.01f));")
        o.append("    }")
    o += ['    if (failures) { printf("%d failure(s)\\n", failures); return 1; }',
          '    printf("codec: all tests passed\\n");', "    return 0;", "}"]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(o) + "\n")
    print("wrote", os.path.relpath(OUT, HERE))


if __name__ == "__main__":
    main()
