#!/usr/bin/env python3
"""Generate src/sender_curves.c from the sender readings taken in the car (docs/sender-calibration.md).

    python tools/make_sender_curves.py sender_readings.csv [src/sender_curves.c]

The CSV has a header line and one row per reading:

    sender,ohms,value
    fuel,73.2,0          # empty: ohms from the centre screen's Settings page, value in percent
    fuel,41.5,50
    fuel,10.4,100
    coolant,302,21       # value in deg C
    oil,10.1,0           # value in kPa

A sender needs at least two readings; a sender with none keeps showing dashes. Readings are sorted by ohms; two readings
with the same resistance, a value outside the sender's range, or a curve that is not monotonic (a level that both rises
and falls with resistance) are refused, because they mean a reading was written down wrong. --selftest runs the checks.
"""
import csv
import os
import sys

RANGES = {"fuel": ("SENDER_FUEL", "FUEL_CURVE", 0.0, 100.0, "%"),
          "oil": ("SENDER_OIL", "OIL_CURVE", 0.0, 1000.0, "kPa"),
          "coolant": ("SENDER_COOLANT", "COOLANT_CURVE", -40.0, 150.0, "deg C")}


def load(path):
    curves = {k: [] for k in RANGES}
    with open(path, newline="", encoding="utf-8") as f:
        rows = [r for r in csv.reader(line for line in f if line.strip() and not line.lstrip().startswith("#"))]
    if not rows or [c.strip().lower() for c in rows[0][:3]] != ["sender", "ohms", "value"]:
        raise SystemExit("the first line must be: sender,ohms,value")
    for n, r in enumerate(rows[1:], start=2):
        name = r[0].strip().lower()
        if name not in RANGES:
            raise SystemExit(f"line {n}: unknown sender {r[0]!r} (fuel, oil or coolant)")
        ohms, value = float(r[1].split("#")[0]), float(r[2].split("#")[0])
        lo, hi = RANGES[name][2], RANGES[name][3]
        if not 0.0 < ohms < 6553.5:
            raise SystemExit(f"line {n}: {ohms} ohm is outside what the board measures")
        if not lo <= value <= hi:
            raise SystemExit(f"line {n}: {value} {RANGES[name][4]} is outside {lo}..{hi}")
        curves[name].append((ohms, value))
    for name, pts in curves.items():
        pts.sort()
        if any(a[0] == b[0] for a, b in zip(pts, pts[1:])):
            raise SystemExit(f"{name}: two readings with the same resistance")
        steps = [b[1] - a[1] for a, b in zip(pts, pts[1:])]
        if any(s > 0 for s in steps) and any(s < 0 for s in steps):
            raise SystemExit(f"{name}: the value rises and falls with resistance; check the readings")
        if len(pts) == 1:
            raise SystemExit(f"{name}: one reading is not a curve; take at least two")
    return curves


def render(curves, source):
    out = ["#include \"senders.h\"", "",
           f"/* GENERATED by tools/make_sender_curves.py from {source}: do not edit; take new readings and regenerate.",
           " * How the readings are taken: docs/sender-calibration.md. A sender with no curve shows dashes. */"]
    calls = []
    for name, (enum, var, _lo, _hi, unit) in RANGES.items():
        pts = curves[name]
        if not pts:
            continue
        body = ", ".join(f"{{ {o:.1f}f, {v:.1f}f }}" for o, v in pts)
        out.append(f"static const sender_pt_t {var}[] = {{ {body} }};   /* ohms, {unit} */")
        calls.append(f"    senders_set_curve({enum}, {var}, (uint8_t)(sizeof {var} / sizeof {var}[0]));")
    out += ["", "void sender_curves_load(void)", "{"] + calls + ["}", ""]
    return "\n".join(out)


def selftest():
    import tempfile
    d = tempfile.mkdtemp()

    def run(text):
        p = os.path.join(d, "r.csv")
        open(p, "w", encoding="utf-8").write(text)
        return load(p)

    c = run("sender,ohms,value\nfuel,73,0\nfuel,10,100\nfuel,40,50\n")
    assert c["fuel"] == [(10.0, 100.0), (40.0, 50.0), (73.0, 0.0)] and c["oil"] == []
    assert "FUEL_CURVE[] = { { 10.0f, 100.0f }, { 40.0f, 50.0f }, { 73.0f, 0.0f } }" in render(c, "r.csv")
    assert "SENDER_OIL" not in render(c, "r.csv")
    for bad in ("sender,ohms,value\nfuel,10,0\nfuel,10,100\n",          # same resistance twice
                "sender,ohms,value\nfuel,10,0\nfuel,20,100\nfuel,30,50\n",  # not monotonic
                "sender,ohms,value\nfuel,10,120\nfuel,20,0\n",           # out of range
                "sender,ohms,value\nfuel,10,0\n",                         # one point
                "sender,ohms,value\nbrake,10,0\nbrake,20,1\n",            # unknown sender
                "ohms,value\n10,0\n"):                                    # no header
        try:
            run(bad)
        except SystemExit:
            continue
        raise AssertionError("accepted: " + bad)
    print("make_sender_curves: selftest ok")


if __name__ == "__main__":
    if sys.argv[1:] == ["--selftest"]:
        selftest()
        sys.exit(0)
    if not 2 <= len(sys.argv) <= 3:
        raise SystemExit(__doc__)
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dst = sys.argv[2] if len(sys.argv) == 3 else os.path.join(here, "src", "sender_curves.c")
    curves = load(sys.argv[1])
    open(dst, "w", encoding="utf-8", newline="\n").write(render(curves, os.path.basename(sys.argv[1])))
    print(f"wrote {dst}: " + ", ".join(f"{k} {len(v)} points" for k, v in curves.items()))
