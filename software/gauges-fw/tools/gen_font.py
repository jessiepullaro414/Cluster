#!/usr/bin/env python3
"""Generate src/font_data.c: anti-aliased 4-bit bitmap fonts from Inter (SIL Open Font License 1.1).

Source font: Inter variable font, https://github.com/rsms/inter (copy at
https://github.com/google/fonts/raw/main/ofl/inter/Inter[opsz,wght].ttf), saved as
software/refs/fonts/Inter.ttf (git-ignored). The OFL text is in ../../../docs/fonts/OFL-Inter.txt.
Embedding rasterised glyphs in firmware is allowed by the OFL; the copyright notice is kept in the
generated file's header.

Faces (pixel size, weight, characters):
  BIG    60 px, weight 500   digits, '-' '.' ' '                 the value in the middle of a gauge
  MED    28 px, weight 500   ASCII 32..126 and the degree sign   secondary values
  SMALL  15 px, weight 500   ASCII 32..126 and the degree sign   labels and scale numbers

The degree sign (U+00B0) is stored at code 0x7F so a plain C string can carry it ("\\x7F" or DEG).
Glyph bitmaps are 4 bits of coverage per pixel, row-major, two pixels per byte (high nibble first).

Run: python tools/gen_font.py        (needs Pillow; the generated file is committed)
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
TTF = os.path.join(os.path.dirname(FW), "refs", "fonts", "Inter.ttf")
OUT = os.path.join(FW, "src", "font_data.c")

FACES = [
    ("BIG", 60, 500, "0123456789-. "),
    ("MED", 28, 500, None),
    ("SMALL", 15, 500, None),
]
FIRST, LAST = 32, 127


def charset(spec):
    if spec is not None:
        return sorted(set(spec), key=ord)
    return [chr(c) for c in range(FIRST, LAST + 1)]


def real_char(c):
    return "°" if c == "\x7f" else c


def main():
    if not os.path.exists(TTF):
        sys.exit("missing %s (see the docstring)" % TTF)
    lines = []
    lines.append("""/* GENERATED by tools/gen_font.py from Inter. Do not edit.
 *
 * Copyright 2020 The Inter Project Authors (https://github.com/rsms/inter)
 * This Font Software is licensed under the SIL Open Font License, Version 1.1
 * (https://scripts.sil.org/OFL; text in docs/fonts/OFL-Inter.txt). The glyph bitmaps below are
 * rasterisations of that font software.
 */
#include "font.h"
""")
    total = 0
    for name, size, weight, spec in FACES:
        font = ImageFont.truetype(TTF, size)
        font.set_variation_by_axes([min(32, max(14, size)), weight])
        chars = charset(spec)
        asc, desc = font.getmetrics()
        glyphs, blob = [], bytearray()
        for ch in chars:
            rc = real_char(ch)
            adv = int(round(font.getlength(rc)))
            bbox = font.getbbox(rc, anchor="ls")           # relative to the origin on the baseline
            if rc.strip() == "" or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
                glyphs.append((len(blob), 0, 0, 0, 0, adv))
                continue
            x0, y0, x1, y1 = bbox
            w, h = x1 - x0, y1 - y0
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), rc, font=font, fill=255, anchor="ls")
            px = list(img.tobytes())
            off = len(blob)
            vals = [min(15, (p + 8) // 17) for p in px]
            if len(vals) % 2:
                vals.append(0)
            for i in range(0, len(vals), 2):
                blob.append((vals[i] << 4) | vals[i + 1])
            glyphs.append((off, w, h, x0, y0, adv))
        total += len(blob) + 8 * len(glyphs)
        first, last = ord(chars[0]), ord(chars[-1])
        full = {ord(c): g for c, g in zip(chars, glyphs)}
        table = [full.get(c, (0, 0, 0, 0, 0, 0)) for c in range(first, last + 1)]
        lines.append("static const uint8_t %s_BITS[%d] = {" % (name, len(blob)))
        for i in range(0, len(blob), 24):
            lines.append("    " + ", ".join("0x%02X" % b for b in blob[i:i + 24]) + ",")
        lines.append("};\n")
        lines.append("static const fglyph_t %s_GLYPHS[%d] = {" % (name, len(table)))
        for (off, w, h, bx, by, adv) in table:
            lines.append("    { %d, %d, %d, %d, %d, %d }," % (off, w, h, bx, by, adv))
        lines.append("};\n")
        lines.append("const font_t FONT_%s = { %s_GLYPHS, %s_BITS, %d, %d, %d, %d };\n" %
                     (name, name, name, first, last, asc, size))
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote %s (about %d bytes of flash)" % (OUT, total))


if __name__ == "__main__":
    main()
