#!/usr/bin/env python3
"""
make_screen_ports_doc.py - writes docs/screen-ports.md from screen_ports.py, so
the pin tables in the document are the ones the boards are built from.

    python tools/make_screen_ports_doc.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import screen_ports as sp  # noqa: E402

OUT = os.path.join(HERE, "..", "docs", "screen-ports.md")

ROLE = {
    "GND": "ground", "+1V8": "1.8 V I/O reference (panel IOVCC if it needs 1.8 V), at most 50 mA",
    "PORTA_5V": "5 V, switched and current-limited on the brain board (U6)",
    "PORTB_5V": "5 V, switched and current-limited on the brain board (U7)",
    "PORTA_RESET": "panel reset, active low (Verdin GPIO_9_DSI)",
    "PORTA_EN": "panel power / bias enable, active high (Verdin GPIO_10_DSI)",
    "PORTA_BL_PWM": "backlight enable and PWM dimming (Verdin PWM_3_DSI)",
    "PORTA_TE": "tearing-effect signal from the panel (Verdin GPIO_IO33)",
    "PORTA_SDA": "I2C data, touch controller (Verdin I2C_2_DSI)",
    "PORTA_SCL": "I2C clock (Verdin I2C_2_DSI)",
    "PORTA_INT": "touch interrupt, open drain, active low (Verdin GPIO_IO34)",
    "PORTA_ID": "analog panel ID (Verdin ADC_2)",
    "PORTB_RESET": "panel reset, active low (Verdin GPIO_4)",
    "PORTB_EN": "panel power enable, active high (Verdin GPIO_5_CSI)",
    "PORTB_BL_PWM": "backlight enable and PWM dimming (Verdin PWM_1)",
    "PORTB_SDA": "I2C data, touch or panel set-up (Verdin I2C_3_HDMI)",
    "PORTB_SCL": "I2C clock (Verdin I2C_3_HDMI)",
    "PORTB_SPI_CLK": "SPI clock, panel set-up for RGB panels (Verdin SPI_1)",
    "PORTB_SPI_MOSI": "SPI data out (Verdin SPI_1)",
    "PORTB_SPI_CS": "SPI chip select, active low (Verdin SPI_1)",
    "PORTB_ID": "analog panel ID (Verdin ADC_3)",
    "RESERVED": "reserved, leave open on both boards",
}


def role(net):
    if net in ROLE:
        return ROLE[net]
    if net.startswith("DSI_"):
        return "MIPI DSI " + net[4:].replace("_", " ")
    if net.startswith("LVDS"):
        return "LVDS channel " + net[4] + " " + net[6:].replace("_", " ")
    return ""


def table(port):
    rows = ["| Contact | Signal | What it is |", "|---|---|---|"]
    for c, net in sorted(port.items()):
        rows.append(f"| {c} | `{net}` | {role(net)} |")
    return "\n".join(rows)


ids = "\n".join(f"| {r:,} ohm | {sp.id_volts(r):.2f} V | {name} |".replace(f"{r:,}", f"{r:,}".replace(",", " "), 1)
                for name, r in sp.PANEL_ID_OHMS.items())

doc = f"""# Screen ports: brain board to panel boards

Generated by `tools/make_screen_ports_doc.py` from `tools/screen_ports.py`, which
the brain board and every panel board are built from. Do not edit the tables by
hand.

The brain board (`brain/`) is the same in every car. Each screen sits on a small
panel board that carries everything that depends on the panel: its connector, its
bias supplies and its backlight driver. A ribbon cable joins the two.

## The two ports

| | Port A (J4) | Port B (J18) |
|---|---|---|
| Video | MIPI DSI, 4 data lanes + clock (Verdin DSI_1) | LVDS, two channels of 4 data pairs + clock (Verdin LVDS0, LVDS1): one single-link or one dual-link panel |
| Connector | Hirose FH12-40S-0.5SH, 40 contacts, 0.5 mm | Hirose FH12-50S-0.5SH, 50 contacts, 0.5 mm |
| Cable | 40-way 0.5 mm FFC, keep it at or under about 150 mm (DSI is a short-reach link) | 50-way 0.5 mm FFC, longer runs are fine for LVDS |
| 5 V | 4 contacts, switched and current-limited at 1.61 / 1.81 / 1.98 A (min / typ / max) by a TPS2557-Q1 | 5 contacts, same limit |
| Control | reset, enable, backlight PWM, TE, touch I2C + interrupt | reset, enable, backlight PWM, I2C, SPI (for RGB panels' set-up) |
| Panel ID | ADC_2 | ADC_3 |

The contact counts differ, so a cable cannot go into the wrong port. Both
connectors are drawn by KiCad's own Hirose FH12 footprints.

Rules for every panel board:

* Use the same connector and the same contact numbers as the table. The cable must
  join contact n to contact n: pick the FFC's contact orientation (same-side or
  opposite-side contacts) that does that for your mounting, and **check it with a
  meter before plugging a panel in**.
* Every control line is 1.8 V logic (the Verdin's I/O level). A panel that needs
  3.3 V logic shifts levels on its own board. +1V8 is a reference and an IOVCC
  supply for 1.8 V panels, not a power feed.
* Make bias, backlight and any 3.3 V rail from the port's 5 V. Stay within the
  port's limit (1.61 A minimum before the switch limits).
* Fit the panel's ID resistor from IDx to GND (table below). The brain board pulls
  IDx up to +1V8 through 10 k and reads it on an ADC; open means no panel.
* The brain board holds reset, enable and the backlight PWM low (100 k) until
  software drives them, and switches the port's 5 V off until software turns it on.

## Port A, MIPI DSI (brain board J4)

{table(sp.PORT_A)}

## Port B, LVDS (brain board J18)

The brain board's J18 is turned 180 degrees (it faces the Verdin socket from above
the module), so its contact numbers are mirrored against the Verdin's pin order:
contact 40 carries LVDS0 CLK N and the 5 V contacts are 45 to 49.

{table(sp.PORT_B)}

## Panel IDs

| Resistor to GND | Voltage at the ADC | Panel |
|---|---|---|
{ids}

## On the brain board

* Each pair runs straight from the Verdin socket to its connector on F.Cu over the
  solid In1 GND plane, planned by `brain/fan_route.py` rather than autorouted:
  0.16 mm tracks, field-solved at 96 to 103 ohm differential
  (`review/dsi_impedance.py`), with no length difference inside a pair. Where the
  socket has a ground pin between two pairs, a ground track runs between them.
* Port A's DSI pairs are about 5.4 mm long; port B's LVDS pairs about 35 mm (they run
  under the module, where tracks are allowed and components are not).

## Not yet known

* Hirose's per-contact current rating (the design assumes 0.5 A) and the FH12's
  contact side: confirm both against the current datasheet before ordering cables.
* Whether the Verdin iMX95 drives the DSI and LVDS outputs as two independent screens
  at once. The i.MX 95 itself can (NXP's triple-display patch), the module's
  datasheet does not say; question 9 in `docs/rfq-drafts.md` section 2.
"""
open(OUT, "w", encoding="utf-8", newline="\n").write(doc)
print("wrote", os.path.normpath(OUT))
